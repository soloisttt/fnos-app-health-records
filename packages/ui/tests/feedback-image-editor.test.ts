import { mount, flushPromises } from "@vue/test-utils";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import FeedbackImageEditor from "../src/components/FeedbackImageEditor.vue";
let loaded: { onload: (() => void) | null };
const ctx = { save: vi.fn(), restore: vi.fn(), clip: vi.fn(), rect: vi.fn(), getImageData: vi.fn((_x: number, _y: number, width: number, height: number) => ({ data: new Uint8ClampedArray(width * height * 4) })), putImageData: vi.fn(), fillRect: vi.fn(), ellipse: vi.fn(), clearRect: vi.fn(), drawImage: vi.fn(), beginPath: vi.fn(), arc: vi.fn(), fill: vi.fn(), moveTo: vi.fn(), lineTo: vi.fn(), stroke: vi.fn(), globalAlpha: 0, globalCompositeOperation: "", strokeStyle: "", fillStyle: "", lineWidth: 0, lineCap: "", lineJoin: "" };
beforeEach(() => {
  vi.clearAllMocks();
  vi.spyOn(URL, "createObjectURL").mockReturnValue("blob:editor-source");
  vi.spyOn(URL, "revokeObjectURL").mockImplementation(() => {});
  vi.spyOn(HTMLCanvasElement.prototype, "getContext").mockReturnValue(ctx as unknown as CanvasRenderingContext2D);
  vi.spyOn(HTMLCanvasElement.prototype, "toBlob").mockImplementation(callback => callback(new Blob(["flattened"], { type: "image/png" })));
  vi.stubGlobal("Image", class { naturalWidth = 1000; naturalHeight = 500; onload = null; onerror = null; src = ""; constructor() { loaded = this; } });
});
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); });
describe("feedback screenshot editor", () => {
  it("maps pointer coordinates, applies mosaic masks and exports flattened pixels", async () => {
    const wrapper = mount(FeedbackImageEditor, { props: { file: new File(["original"], "original.jpg", { type: "image/jpeg" }) }, global: { stubs: { Teleport: true } } });
    loaded.onload?.(); await flushPromises();
    await wrapper.findAll(".editor-modes button")[1].trigger("click");
    const canvas = wrapper.get("canvas");
    Object.assign(canvas.element, { setPointerCapture: vi.fn(), hasPointerCapture: () => false });
    vi.spyOn(HTMLCanvasElement.prototype, "getBoundingClientRect").mockReturnValue({ left: 10, top: 20, width: 500, height: 250 } as DOMRect);
    await canvas.trigger("pointerdown", { pointerId: 1, button: 0, clientX: 60, clientY: 70 });
    await canvas.trigger("pointermove", { pointerId: 1, clientX: 110, clientY: 120 });
    await canvas.trigger("pointerup", { pointerId: 1, clientX: 110, clientY: 120 });
    expect(ctx.putImageData).toHaveBeenCalled();
    expect(ctx.clip).toHaveBeenCalled();
    expect(ctx.globalAlpha).toBe(1);
    expect(ctx.rect).toHaveBeenCalledWith(100, 100, 100, 100);
    expect(wrapper.get('[aria-label="撤销上一步"]').attributes("disabled")).toBeUndefined();
    await wrapper.get(".editor-save").trigger("click"); await flushPromises();
    const file = wrapper.emitted("save")?.[0][0] as File;
    expect(file.name).toBe("feedback-edited.png");
    expect(file.type).toBe("image/png");
    expect(await file.text()).toBe("flattened");
    wrapper.unmount();
    expect(URL.revokeObjectURL).toHaveBeenCalledWith("blob:editor-source");
  });
  it("pixelates reverse-dragged ellipses and supports undo", async () => {
    const wrapper = mount(FeedbackImageEditor, { props: { file: new File(["image"], "image.png") }, global: { stubs: { Teleport: true } } });
    loaded.onload?.(); await flushPromises();
    await wrapper.findAll(".editor-modes button")[1].trigger("click");
    await wrapper.findAll('[aria-label="打码形状"] button')[1].trigger("click");
    expect(wrapper.find(".mask-dropdown").exists()).toBe(false);
    expect(wrapper.find(".width-picker").exists()).toBe(false);
    const canvas = wrapper.get("canvas");
    Object.assign(canvas.element, { setPointerCapture: vi.fn(), hasPointerCapture: () => false });
    vi.spyOn(HTMLCanvasElement.prototype, "getBoundingClientRect").mockReturnValue({ left: 0, top: 0, width: 1000, height: 500 } as DOMRect);
    await canvas.trigger("pointerdown", { pointerId: 2, button: 0, clientX: 300, clientY: 200 });
    await canvas.trigger("pointerup", { pointerId: 2, clientX: 100, clientY: 100 });
    expect(ctx.ellipse).toHaveBeenCalledWith(200, 150, 100, 50, 0, 0, Math.PI * 2);
    expect(ctx.clip).toHaveBeenCalled();
    expect(ctx.globalAlpha).toBe(1);
    await wrapper.get('[aria-label="撤销上一步"]').trigger("click");
    expect(wrapper.get('[aria-label="撤销上一步"]').attributes("disabled")).toBeDefined();
    wrapper.unmount();
  });
  it("pinches and pans without committing the first finger's stroke", async () => {
    const wrapper = mount(FeedbackImageEditor, { props: { file: new File(["image"], "image.png") }, global: { stubs: { Teleport: true } } });
    loaded.onload?.(); await flushPromises();
    const canvas = wrapper.get("canvas");
    Object.assign(canvas.element, { setPointerCapture: vi.fn(), hasPointerCapture: () => false });
    vi.spyOn(HTMLCanvasElement.prototype, "getBoundingClientRect").mockReturnValue({ left: 0, top: 0, width: 1000, height: 500 } as DOMRect);
    await canvas.trigger("pointerdown", { pointerId: 1, pointerType: "touch", button: 0, clientX: 100, clientY: 100 });
    await canvas.trigger("pointermove", { pointerId: 1, pointerType: "touch", clientX: 110, clientY: 100 });
    await canvas.trigger("pointerdown", { pointerId: 2, pointerType: "touch", button: 0, clientX: 210, clientY: 100 });
    await canvas.trigger("pointermove", { pointerId: 2, pointerType: "touch", clientX: 310, clientY: 100 });
    expect(wrapper.get(".reset-view").text()).toContain("200%");
    expect(wrapper.get("canvas").attributes("style")).toContain("scale(2)");
    await canvas.trigger("pointerup", { pointerId: 2, pointerType: "touch", clientX: 310, clientY: 100 });
    await canvas.trigger("pointermove", { pointerId: 1, pointerType: "touch", clientX: 150, clientY: 100 });
    await canvas.trigger("pointerup", { pointerId: 1, pointerType: "touch", clientX: 150, clientY: 100 });
    expect(wrapper.get('[aria-label="撤销上一步"]').attributes("disabled")).toBeDefined();
    await wrapper.get(".reset-view").trigger("click");
    expect(wrapper.get("canvas").attributes("style")).toContain("translate(0px, 0px) scale(1)");
    wrapper.unmount();
  });
  it("can cancel without exporting or replacing the original", async () => {
    const wrapper = mount(FeedbackImageEditor, { props: { file: new File(["original"], "original.png") }, global: { stubs: { Teleport: true } } });
    await wrapper.get('[aria-label="关闭图片编辑"]').trigger("click");
    expect(wrapper.emitted("cancel")).toHaveLength(1);
    expect(wrapper.emitted("save")).toBeUndefined();
    wrapper.unmount();
  });
});
